#!/usr/bin/env python3
"""Build one self-contained userscript; initialize only the matching site's engine."""
import json
from pathlib import Path
import re

root = Path(__file__).resolve().parent.parent
release = json.loads((root / 'scripts/bundle-config.json').read_text())
raw = 'https://raw.githubusercontent.com/sudazz777/WangZhanFanYi/refs/heads/main'
assert re.fullmatch(r'\d{1,6}(?:\.\d{1,6}){1,3}', release['version'])
config = {key: release[key] for key in ['id', 'name', 'namespace', 'version']}
config.update(metaUrl=f"{raw}/updates/{release['id']}.meta.js",
              installUrl=f"{raw}/{release['filename']}")
fields = [
    ('name', release['name']), ('namespace', release['namespace']),
    ('version', release['version']),
    ('description', '一个脚本翻译 Artlist、Musicbed 和 GitHub，自动识别网站，支持检查更新。'),
]
for site in release['sites']:
    fields.extend(('match', f'https://{host}/*') for host in site['hosts'])
fields += [('updateURL', config['metaUrl']), ('downloadURL', f"{raw}/{release['filename']}"),
           ('run-at', 'document-start'), ('noframes', ''),
           *[('grant', grant) for grant in ['GM_getValue', 'GM_setValue', 'GM_registerMenuCommand', 'GM_xmlhttpRequest']],
           ('connect', 'translate.googleapis.com'), ('connect', 'raw.githubusercontent.com'),
           ('license', 'GPL-3.0-or-later')]
header = '// ==UserScript==\n' + '\n'.join('// @'+key.ljust(13)+value for key, value in fields) + '\n// ==/UserScript=='
updater = (root / 'scripts/script-update-module.js').read_text().rstrip()
shared_updater = (root / 'scripts/bundle-update-module.js').read_text().rstrip()
parts = [header, '\n// Generated by scripts/build-bundle.py; edit the individual site engines to maintain translations.',
         "(() => {\n  'use strict';", '  const SCRIPT_UPDATE = '+json.dumps(config, ensure_ascii=False, separators=(',', ':'))+';',
         (root / 'scripts/render-core.js').read_text().rstrip(),
         shared_updater,
         '  const hostname = location.hostname;']
for site in release['sites']:
    source = (root / f"{site['id']}-zh-CN.user.js").read_text()
    body = source.split('// ==/UserScript==', 1)[1].strip()
    if site['id'] in ['artlist', 'musicbed']:
        body = '// '+site['name']+' translation engine: originally distributed under the MIT license.\n'+body
    # One release identity drives manual and native updates on all supported sites.
    body, count = re.subn(r'  // BEGIN SCRIPT UPDATE CONFIG\n.*?  // END SCRIPT UPDATE CONFIG\n', '', body, count=1, flags=re.S)
    assert count == 1, site['id']
    # Legacy standalone releases keep their engines. The bundle uses one shared
    # rendering core, parameterized by each site's scan/translate/protection rules.
    start, end = body.index('  function installRevealStyle()'), body.index('  function* prune()')
    binding = '  const renderCore = createRenderCore({site:'+json.dumps(site['id'])+', enabled:()=>settings.enabled, skip:SKIP, scan, translate});\n'
    binding += '  const {schedule, scheduleAttribute, installRevealStyle, requestScan, scanTasks} = renderCore;\n'
    body = body[:start] + binding + body[end:]
    for declaration in ['const roots = new Set();', 'const scanTasks = [];', 'const attributeJobs = new Map();',
                        'let scanTimer = 0;', 'let scanQueued = false;', 'let scanGeneration = 0;',
                        'const maskableRoots = new WeakSet();', 'const pendingMasks = new Map();',
                        'let revealStyle;', 'const MASK_LIMIT = 180;']:
        assert body.count('  '+declaration+'\n') == 1, (site['id'], declaration)
        body = body.replace('  '+declaration+'\n', '', 1)
    reset = ('    clearTimeout(scanTimer); scanTimer = 0;\n'
             '    scanGeneration++; scanQueued = false;\n'
             '    for (const root of [...pendingMasks.keys()]) reveal(root);\n')
    assert body.count(reset) == 1, site['id']
    body = body.replace(reset, '    renderCore.reset();\n', 1)
    body = body.replace('    roots.clear(); attributeJobs.clear(); scanTasks.length = 0;\n', '', 1)
    assert not re.search(r'\b(scanTimer|scanQueued|scanGeneration|pendingMasks|maskableRoots|revealStyle|MASK_LIMIT|attributeJobs|roots)\b', body), site['id']
    module = '  // BEGIN SCRIPT UPDATE MODULE\n'+updater+'\n  // END SCRIPT UPDATE MODULE'
    assert body.count(module) == 1, site['id']
    body = body.replace(module, '  const {mountScriptUpdate, checkScriptUpdate} = createScriptUpdater(() => host);', 1)
    if site['id'] == 'github':
        # Selection translation is still available from Tampermonkey's menu.
        for old, new in [
            ('    ui.selection.disabled = busy;\n', ''),
            ("    ui.selection.textContent = busy ? '正在翻译所选文字…' : '翻译选中文字（在线）';\n", ''),
            ('<button id="selection"></button>', ''),
            ("'rescan', 'selection', 'clear'", "'rescan', 'clear'"),
            ('    ui.selection.onclick = translateSelection;\n', ''),
        ]:
            assert body.count(old) == 1, old
            body = body.replace(old, new, 1)
    body = body.replace(f"中 / EN · {site['name']} 翻译", f"中 / EN · 网站翻译（{site['name']}）")
    condition = ' || '.join('hostname === '+json.dumps(host) for host in site['hosts'])
    parts.append(f"  if ({condition}) {{\n{body}\n    return;\n  }}")
parts.append('})();\n')
(root / release['filename']).write_text('\n'.join(parts))
(root / f"updates/{release['id']}.meta.js").write_text(header+'\n')
print(f"Built {release['filename']} v{release['version']} ({len(release['sites'])} sites)")
